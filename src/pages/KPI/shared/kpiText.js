export function makeKpiText(locale) {
  const lang = TEXT[locale] ? locale : String(locale ?? "").slice(0, 2) in TEXT ? String(locale).slice(0, 2) : "en";
  return (key, vars) => {
    let s = TEXT[lang][key] ?? TEXT.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

export function useKpiText(locale) {
  return useMemo(() => makeKpiText(locale), [locale]);
}