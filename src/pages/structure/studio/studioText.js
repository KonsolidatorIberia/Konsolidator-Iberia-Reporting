// Etiqueta (en cualquier idioma) o id → id. Para leer el Excel aunque se
// haya rellenado con los nombres en lugar de los códigos.
export function labelIndex(prefix) {
  const out = new Map();
  Object.values(DICTS).forEach(d => Object.entries(d).forEach(([k, v]) => {
    if (k.startsWith(prefix)) {
      const id = k.slice(prefix.length);
      out.set(String(v).trim().toLowerCase(), id);
      out.set(id.toLowerCase(), id);
    }
  }));
  return out;
}
