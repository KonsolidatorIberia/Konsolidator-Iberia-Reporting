const DICTS = { es: ES, en: EN, da: DA, pt: PT };

export function makeTx(locale) {
  const lang = DICTS[String(locale ?? "").slice(0, 2)] ? String(locale).slice(0, 2) : "en";
  const d = DICTS[lang];
  const tx = (key, vars) => {
    let s = d[key] ?? EN[key] ?? ES[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
    return s;
  };
  tx.lang = lang;
  return tx;
}

export function useTx() {
  const locale = useLocale();
  return makeTx(locale);
}

// Formatos
export const fmtPctN = (n, lang) => (n == null || n === "" ? "—"
  : new Intl.NumberFormat(lang === "en" ? "en-GB" : lang === "da" ? "da-DK" : lang === "pt" ? "pt-PT" : "es-ES", { maximumFractionDigits: 2 }).format(Number(n)));
export const fmtDate = (iso, lang) => {
  if (!iso) return "—";
  const d = new Date(`${iso}T00:00:00Z`);
  if (Number.isNaN(d.getTime())) return iso;
  return new Intl.DateTimeFormat(lang === "en" ? "en-GB" : lang === "da" ? "da-DK" : lang === "pt" ? "pt-PT" : "es-ES",
    { day: "2-digit", month: "short", year: "numeric", timeZone: "UTC" }).format(d);
};

// Texto de un error de la base de datos
export function errorText(tx, err) {
  const { code, detail, message } = err ?? {};
  const key = `e_${code}`;
  const vars = { ...(detail ?? {}), message: message ?? "" };
  if (vars.entities && Array.isArray(vars.entities)) vars.entities = vars.entities.join(", ");
  ["date", "start_date"].forEach(k => { if (vars[k]) vars[k] = fmtDate(vars[k], tx.lang); });
  if (vars.total != null) vars.total = fmtPctN(vars.total, tx.lang);
  const s = tx(key, vars);
  return s === key ? tx("e_unknown", vars) : s;
}

// Clasificación y método que se proponen por el % de voto del grupo
export function suggestByVoting(v) {
  const n = Number(v) || 0;
  if (n > 50) return { classification: "subsidiary", method: "full" };
  if (n >= 20) return { classification: "associate", method: "equity" };
  return { classification: "investment", method: "none" };
}
