export function makeText(locale) {
  const lang = TEXT[locale] ? locale : "en";
  return (key, vars) => {
    let s = key.startsWith("adm_") || !(key in TEXT.en)
      ? t(locale, key)
      : (TEXT[lang][key] ?? TEXT.en[key]);
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}